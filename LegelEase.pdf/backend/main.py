from __future__ import annotations

import os
from functools import lru_cache
from pathlib import Path

from dotenv import load_dotenv
from fastapi import FastAPI, UploadFile, File
from fastapi.middleware.cors import CORSMiddleware
from fastapi.staticfiles import StaticFiles
from fastapi.responses import FileResponse
from pydantic import BaseModel, Field

load_dotenv()


# =========================
# SETTINGS
# =========================

class Settings(BaseModel):
    app_name: str = Field(
        default_factory=lambda: os.getenv("APP_NAME", "LegalEase")
    )

    company_name: str = Field(
        default_factory=lambda: os.getenv("COMPANY_NAME", "LegalEase")
    )

    gemini_api_key: str | None = Field(
        default_factory=lambda: os.getenv("GEMINI_API_KEY") or None
    )

    gemini_model: str = Field(
        default_factory=lambda: os.getenv(
            "GEMINI_MODEL",
            "gemini-3.8-flash"
        )
    )

    host: str = Field(
        default_factory=lambda: os.getenv(
            "HOST",
            "127.0.0.1"
        )
    )

    port: int = Field(
        default_factory=lambda: int(
            os.getenv("PORT", "8000")
        )
    )

    backend_url: str = Field(
        default_factory=lambda: os.getenv(
            "BACKEND_URL",
            "http://127.0.0.1:8000"
        )
    )

    cors_origins: list[str] = Field(
        default_factory=lambda: [
            item.strip()
            for item in os.getenv(
                "CORS_ORIGINS",
                "http://localhost:8501,http://127.0.0.1:8501"
            ).split(",")
            if item.strip()
        ]
    )


@lru_cache
def get_settings() -> Settings:
    return Settings()


settings = get_settings()


# =========================
# FASTAPI APP
# =========================

app = FastAPI(
    title=settings.app_name,
    description="LegalEase - AI Powered Legal Document Assistant",
    version="1.0.0",
)


# =========================
# FRONTEND
# =========================

BASE_DIR = Path(__file__).resolve().parent.parent
FRONTEND_DIR = BASE_DIR / "frontend"

app.mount(
    "/static",
    StaticFiles(directory=FRONTEND_DIR),
    name="static"
)


@app.get("/", include_in_schema=False)
def serve_frontend():
    return FileResponse(FRONTEND_DIR / "index.html")


# =========================
# CORS
# =========================

app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.cors_origins,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


# =========================
# BASIC API
# =========================

@app.get("/health")
def health():
    return {
        "status": "healthy",
        "service": "LegalEase API",
    }


# =========================
# GENERATE DOCUMENT
# =========================

class GenerateRequest(BaseModel):
    request: str


@app.post("/generate")
def generate_document(data: GenerateRequest):

    request_text = data.request.strip()

    if not request_text:
        return {
            "message": "Please provide document requirements."
        }

    # Try Gemini AI
    if settings.gemini_api_key:

        try:
            from google import genai

            client = genai.Client(
                api_key=settings.gemini_api_key
            )

            prompt = f"""
You are LegalEase, an AI-assisted legal document drafting assistant.

Create a clear and professionally structured draft based on
the following user requirements.

User requirements:
{request_text}

Include appropriate sections such as:
- Title
- Parties
- Date
- Purpose
- Terms and Conditions
- Responsibilities
- Payment terms if applicable
- Confidentiality if applicable
- Termination if applicable
- Dispute resolution if applicable
- Signature section

Use clear professional language.

Important:
This is an AI-generated draft and should not be treated as
professional legal advice.
"""

            response = client.models.generate_content(
                model=settings.gemini_model,
                contents=prompt
            )

            generated_text = response.text

            return {
                "success": True,
                "document": generated_text
            }

        except Exception as e:

            return {
                "success": False,
                "document": create_demo_document(request_text),
                "ai_error": str(e)
            }

    # Demo fallback when Gemini API key is not configured
    return {
        "success": True,
        "document": create_demo_document(request_text)
    }


